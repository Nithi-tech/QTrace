// Backend base URL is environment-specific configuration (CLAUDE.md #18), not a secret -
// it never contains provider API keys. Read from local.properties (gitignored) so each
// developer/CI target can point at their own backend without editing source.
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun localOrDefault(key: String, default: String): String = localProperties.getProperty(key) ?: default

